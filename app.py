def search_real_jobs(
    api_key,
    career,
    location
):

    if not api_key:

        return [], (
            "Please enter your SerpApi API key "
            "in the sidebar."
        )

    params = {

        "engine": "google_jobs",

        "q": career,

        "location": location,

        "hl": "en",

        "api_key": api_key
    }

    try:

        response = requests.get(
            "https://serpapi.com/search.json",
            params=params,
            timeout=30
        )

        if response.status_code != 200:

            return [], (
                f"SerpApi returned HTTP "
                f"{response.status_code}"
            )

        data = response.json()

        jobs = []

        for job in data.get(
            "jobs_results",
            []
        ):

            title = job.get("title")

            company = job.get(
                "company_name"
            )

            location_value = job.get(
                "location",
                "Not specified"
            )

            description = job.get(
                "description",
                ""
            )

            apply_url = None

            for option in job.get(
                "apply_options",
                []
            ):

                link = option.get("link")

                if valid_url(link):

                    apply_url = link

                    break

            # IMPORTANT:
            # No title/company/link =
            # do not display the job.

            if not title:
                continue

            if not company:
                continue

            if not apply_url:
                continue

            extensions = job.get(
                "detected_extensions",
                {}
            )

            jobs.append({

                "title": title,

                "company": company,

                "location":
                    location_value,

                "description":
                    description,

                "apply_url":
                    apply_url,

                "salary":
                    extensions.get(
                        "salary",
                        "Not specified"
                    ),

                "posted":
                    extensions.get(
                        "posted_at",
                        "Not specified"
                    ),

                "schedule":
                    extensions.get(
                        "schedule_type",
                        "Not specified"
                    )
            })

        return jobs, None

    except Exception as error:

        return [], str(error)


