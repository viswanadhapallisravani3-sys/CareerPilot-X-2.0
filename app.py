def normalize(text):

    return re.sub(
        r"[^a-zA-Z0-9+#. ]",
        "",
        str(text).lower()
    )


def calculate_skill_match(
    user_skills,
    required_skills
):

    user = {
        normalize(skill)
        for skill in user_skills
    }

    required = {
        normalize(skill)
        for skill in required_skills
    }

    if not required:
        return 0

    matched = user.intersection(required)

    return round(
        len(matched) /
        len(required) *
        100
    )


def get_missing_skills(
    user_skills,
    required_skills
):

    user = {
        normalize(skill)
        for skill in user_skills
    }

    return [
        skill
        for skill in required_skills
        if normalize(skill) not in user
    ]


def valid_url(url):

    if not url:
        return False

    url = str(url).strip()

    if not url.startswith(
        ("http://", "https://")
    ):
        return False

    blocked = [
        "google.com/search",
        "bing.com/search",
        "yahoo.com/search"
    ]

    for domain in blocked:

        if domain in url.lower():
            return False

    return True


